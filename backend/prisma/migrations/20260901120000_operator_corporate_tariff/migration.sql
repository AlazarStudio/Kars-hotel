-- Корпоративный тариф гостиницы для оператора.
--
-- Гостиница работает по своим тарифам — это её дело и её цены. С оператором
-- она подписывает договор, и по нему для оператора заводится ОТДЕЛЬНЫЙ тариф.
-- Так же устроен TravelLine и так же понимает это администратор гостиницы:
-- «корпоративный тариф для такого-то», а не «скидка в общем прайсе».
--
-- Ключевое здесь не признак, а ПОДТВЕРЖДЕНИЕ. Тариф заводит гостиница, а
-- платит по нему оператор, поэтому цены обязан проверить оператор — построчно
-- против ценового приложения договора. Неподтверждённый тариф не применяется
-- вовсе: селим по стандартному, и цена честно помечается внедоговорной.
-- Молчаливое «наверное, всё верно» здесь стоит денег на каждой брони.

-- Вердикт — РЕШЕНИЕ человека, и только оно тут и хранится.
CREATE TYPE "operator_review_verdict" AS ENUM ('CONFIRMED', 'REJECTED');

ALTER TABLE "rate_plan"
  ADD COLUMN "for_operator"       BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN "operator_contract"  TEXT,
  ADD COLUMN "review_verdict"     "operator_review_verdict",
  ADD COLUMN "reviewed_at"        TIMESTAMP(3),
  ADD COLUMN "reviewed_by"        TEXT,
  ADD COLUMN "review_documents"   TEXT,
  ADD COLUMN "review_fingerprint" TEXT,
  ADD COLUMN "review_notes"       JSONB;

-- СВЕЖЕСТЬ подтверждения колонкой не хранится намеренно.
--
-- Подтверждали не «тариф вообще», а соответствие КОНКРЕТНЫМ ценам договора.
-- Вышла ДС, поменялись цены — сверяли уже с другим документом, и подтверждение
-- обязано слететь. Хранить это флагом значит помнить сбрасывать его в каждом
-- месте, куда приезжают цены: сегодня это зеркало из Авии, завтра будет ещё
-- одно — и однажды не сбросят. Поэтому в момент сверки запоминается ОТПЕЧАТОК
-- набора приложений, а состояние вычисляется сравнением с текущим.
COMMENT ON COLUMN "rate_plan"."review_fingerprint" IS
  'Отпечаток набора ценовых приложений на момент сверки; расхождение с текущим = подтверждение устарело';

-- Корпоративный тариф для оператора у гостиницы ОДИН.
--
-- Периоды внутри тарифа задаются ставками по датам, так что второй тариф не
-- нужен даже под новый год цен. А нужен он был бы ровно затем, чтобы потом
-- выбирать между двумя — то есть за произвол, который в Авии на этой же неделе
-- пришлось убирать у договоров гостиницы. Один активный — один ответ.
CREATE UNIQUE INDEX "rate_plan_operator_key"
  ON "rate_plan" ("tenant_id")
  WHERE "for_operator" AND "is_active";

-- Корпоративный тариф НЕ МОЖЕТ БЫТЬ НАСЛЕДНИКОМ.
--
-- Наследование в PMS живое: дочерний тариф считает цену от родителя через
-- модификатор. Значит правка родительского прайса меняет и корпоративные
-- цены — а подтверждение оператора при этом продолжает висеть, и висит уже
-- про другие цифры. Это ровно та тихая ошибка, ради которой затевалось
-- подтверждение.
--
-- «Наследовать из существующего тарифа» при заведении остаётся, но как
-- ЗАПОЛНЕНИЕ: ставки копируются один раз и дальше живут своей жизнью. Тариф,
-- по которому платят по договору, обязан нести свои цифры сам.
ALTER TABLE "rate_plan"
  ADD CONSTRAINT "rate_plan_operator_no_parent"
  CHECK (NOT "for_operator" OR "parent_rate_plan_id" IS NULL);
