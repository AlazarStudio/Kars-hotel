-- Д4/А3 · договорные блоки номеров: держится ли номер за партнёром.
--
-- У оператора есть договорные блоки — конкретные номера, которые отель держит
-- за ним. В PMS этого понятия не было вовсе: и отель, и партнёр помнили о
-- договорённости в переписке, а расхождение всплывало в день заезда.
--
-- QUOTA — гарантированный блок по договору; RESERVE — держим сверх квоты,
-- подстраховка на пиковые дни (партнёр видит, но знает, что это не гарантия).
--
-- Признак ИНФОРМАЦИОННЫЙ и продажу номера в PMS не блокирует. Блокировать
-- значило бы вынести коммерческую договорённость в техническое ограничение —
-- а договорённости меняются быстрее, чем данные в базе, и отель всё равно
-- продаст номер, если так решил. Задача признака — чтобы обе стороны видели
-- одно и то же и расхождение было заметно, а не молча случилось.
CREATE TYPE "RoomPartnerHold" AS ENUM ('NONE', 'QUOTA', 'RESERVE');

-- DEFAULT NONE без бэкфилла: существующие номера ни за кем не держатся, и
-- задним числом объявлять их квотой нельзя — это коммерческий факт, а не
-- техническая деталь.
ALTER TABLE "room"
  ADD COLUMN "partner_hold" "RoomPartnerHold" NOT NULL DEFAULT 'NONE';

CREATE INDEX "room_tenant_id_partner_hold_idx" ON "room"("tenant_id", "partner_hold");
