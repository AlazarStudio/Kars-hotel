-- Kars Avia: «со стороны гостиницы в бронях видна дата, но не видно время
-- прибытия»).
--
-- Даты брони остаются датами (check_in / check_out — DATE): по ним считаются
-- ночи, места и цена. Время прилёта и отъезда из заявки партнёра и рейс едут
-- рядом: у квартир нет круглосуточной стойки, и без времени экипаж встречать
-- некому.
--
-- Текстом «ГГГГ-ММ-ДДTЧЧ:ММ», а не TIMESTAMP: это местное время города, как его
-- видит диспетчер. Метку времени пересчитали бы по поясу сервер и браузер, и
-- прилёт в 02:00 стал бы 05:00. Проверку формата делает партнёрский API.
-- У старых броней время неизвестно и остаётся пустым — честнее, чем выдумать.
ALTER TABLE "reservation"
  ADD COLUMN "arrival_at"   VARCHAR(16),
  ADD COLUMN "departure_at" VARCHAR(16),
  ADD COLUMN "flight"       VARCHAR(64);
