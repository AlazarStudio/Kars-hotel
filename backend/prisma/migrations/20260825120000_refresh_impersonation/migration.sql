-- Продление сессии, открытой по ссылке из Kars Avia.
--
-- Такая сессия — это диспетчер, работающий ВНУТРИ гостиницы: `sub` — он сам,
-- `tid` — гостиница, права — по её роли «Владелец». Раньше ей не выдавалась
-- refresh-кука вовсе, и через час работы человека выбрасывало на форму входа.
--
-- Просто выдать куку мало: при обновлении сервер перевыпускает токен ПО
-- ЗАПИСИ, а в записи до сих пор были только «кто» и «в каком тенанте». Для
-- диспетчера этого не хватает: он числится в тенанте платформы, и по такой
-- записи вернулся бы токен платформы — то есть обновление молча выкидывало бы
-- человека из гостиницы в общую панель, с другими правами.
--
-- Поэтому запись помнит, что она impersonation и от чьего имени: при
-- обновлении личность и область восстанавливаются те же.
ALTER TABLE "refresh_token"
  ADD COLUMN "impersonated_by" UUID;

