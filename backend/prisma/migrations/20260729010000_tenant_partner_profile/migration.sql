-- В2/В4 · профиль гостиницы для партнёрского каталога.
--
-- Партнёр (Kars Avia) показывает карточку отеля диспетчеру, который выбирает,
-- куда селить экипаж. Звёзд для этого мало: нужны гостевой рейтинг, заявленная
-- вместимость, «сколько ехать до аэропорта» и расписание питания — то, по чему
-- выбор реально делается. Контракт эти поля уже описывает, но заполнять их
-- было нечем: в `tenant` их просто не существовало, и работали они только на
-- заглушке hotel-mock.
--
-- Все поля NULL-able без бэкфилла: неизвестное значение честнее выдуманного.
-- Партнёрская карточка опускает пустые поля, а не показывает «0 звёзд» и
-- «0 мест».
ALTER TABLE "tenant"
  -- Гостевой рейтинг 0..5. Отдельно от stars: звёзды — официальная категория,
  -- рейтинг — как там на самом деле.
  ADD COLUMN "guest_rating" DOUBLE PRECISION,
  -- Заявленная вместимость в местах. Считать по номерам нельзя: часть фонда
  -- может быть выключена, а партнёру нужна величина «сколько отель берёт».
  ADD COLUMN "capacity" INTEGER,
  -- Аэропорт, который обслуживает гостиница, и типичное время в пути.
  -- Минуты, а не километры: диспетчер планирует время подачи машины.
  ADD COLUMN "airport_code" TEXT,
  ADD COLUMN "airport_minutes" INTEGER,
  -- Окна питания свободными строками. Не структурируем в «с/до»: у отелей
  -- встречается «07:00–10:00, 10:30–11:00 для экипажей», и схема на два поля
  -- это потеряет.
  ADD COLUMN "meal_breakfast" TEXT,
  ADD COLUMN "meal_lunch" TEXT,
  ADD COLUMN "meal_dinner" TEXT,
  -- Инфраструктура рядом: «аптека 200 м», «остановка у выхода».
  ADD COLUMN "infrastructure" JSONB NOT NULL DEFAULT '[]'::jsonb;
