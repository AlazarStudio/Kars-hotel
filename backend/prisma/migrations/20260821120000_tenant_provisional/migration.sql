-- Гостиница, заведённая «на разок» из сбойной заявки.
--
-- Ночью при сбое людей селят куда придётся: с гостиницей договариваются по
-- телефону, договора с ней нет и, возможно, не будет. Такая запись нужна,
-- чтобы заявка знала, куда увезли людей, — но в общем каталоге ей не место:
-- диспетчер, размещающий экипаж планово, не должен на неё натыкаться.
--
-- Отдельно от `partner_visible`: тот отвечает на «показывать ли сейчас»
-- (гостиница временно не берёт заявки), а этот — на «что это вообще за
-- запись». Одним флагом два разных смысла не выразить: сняв видимость у
-- разовой, мы бы потеряли различие между «пока не предлагаем» и «зашли на
-- одну ночь», и через полгода никто не вспомнит, почему она скрыта.
--
-- Заключили договор → снимаем признак, и гостиница появляется везде.
ALTER TABLE "tenant"
  ADD COLUMN "provisional" BOOLEAN NOT NULL DEFAULT false;

-- Каталог фильтрует по трём полям сразу; индекс тот же, что уже используется
-- для выборки видимых отелей.
CREATE INDEX "tenant_provisional_idx" ON "tenant" ("provisional");
