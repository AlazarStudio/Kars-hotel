-- план 13.3).
--
-- Каждый диспетчер Авиа заходил в PMS с ролью SUPER_ADMIN: видел сотрудников
-- всех гостиниц (ФИО, почта), заводил и выключал гостиницы, менял настройки
-- платформы. Флаг is_dispatcher менял только подпись в интерфейсе, а права
-- оставались суперадминскими — и продление сессии выводило суперадмина из
-- кода роли. Теперь у диспетчера своя роль; что ей можно — решают гарды
-- панели платформы (список гостиниц и вход «от имени»), а не подпись.
--
-- Новое значение перечисления нельзя использовать в той же транзакции,
-- поэтому назначение роли — следующей миграцией.
ALTER TYPE "RoleCode" ADD VALUE IF NOT EXISTS 'DISPATCHER';
