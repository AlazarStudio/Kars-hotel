-- УДАЛЕНИЕ «В АРХИВ» НОМЕРА И ГОСТИНИЦЫ (25.10.2026, решение владельца:
-- «удаление не должно удалять данные из бд»).
--
-- До этого удаление номера стирало строку room (DELETE), а удаление пустой
-- гостиницы — все строки гостиницы во всех таблицах. Теперь удаление ставит
-- пометку: кто и когда убрал запись. Сама запись, её брони, счета и история
-- остаются, и её можно восстановить.
--
-- Архивная запись дополнительно выключается (is_active = false): продажа,
-- шахматка, наличие, вход сотрудников и каталог партнёра и так смотрят только
-- на включённые — архивное не всплывёт там, где фильтр по архиву забыли.
--
-- Индексы не нужны: архивных строк единицы, списки и так идут по tenant_id.
-- У существующих строк пометок нет — архив начинается с этой миграции.
ALTER TABLE "room"
  ADD COLUMN "archived_at" TIMESTAMP(3),
  ADD COLUMN "archived_by" UUID;

ALTER TABLE "tenant"
  ADD COLUMN "archived_at" TIMESTAMP(3),
  ADD COLUMN "archived_by" UUID;
