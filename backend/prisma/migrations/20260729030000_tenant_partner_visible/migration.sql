-- В3 · видимость отеля в каталоге партнёра.
--
-- Снять отель с предложения оператору было нечем: единственный переключатель —
-- `is_active`, но он выключает тенанта ЦЕЛИКОМ, вместе со входом сотрудников.
-- То есть «мы пока не берём заявки» означало «отель не может работать» — и
-- этим, естественно, не пользовались, а просто отказывали по телефону.
--
-- Отдельный флаг: отель работает как обычно, просто в каталоге партнёра его
-- нет. DEFAULT true и без бэкфилла: существующие отели видимы, как и были.
ALTER TABLE "tenant"
  ADD COLUMN "partner_visible" BOOLEAN NOT NULL DEFAULT true;
