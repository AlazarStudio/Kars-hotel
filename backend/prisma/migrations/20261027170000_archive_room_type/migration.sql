-- УДАЛЕНИЕ КАТЕГОРИИ НОМЕРОВ «В АРХИВ» (27.10.2026, жалоба гостиниц).
--
-- С 25.10 «Удалить номер» не стирает строку room, а ставит пометку архива.
-- Архивные номера по-прежнему ссылаются на свою категорию (внешний ключ
-- room.room_type_id, ON DELETE RESTRICT), поэтому категорию, из которой
-- удалили все номера, нельзя было удалить: проверка насчитывала «16 номеров»,
-- а сам DELETE упёрся бы в ключ. Стирать строки владелец запретил 25.10 —
-- значит, категория тоже уходит в архив: кто и когда убрал.
--
-- Только добавление столбцов: прежний код с ними работает. Индексы не нужны —
-- категорий у гостиницы единицы, списки идут по tenant_id.
ALTER TABLE "room_type"
  ADD COLUMN "archived_at" TIMESTAMP(3),
  ADD COLUMN "archived_by" UUID;
