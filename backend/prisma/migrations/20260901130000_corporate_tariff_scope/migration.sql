-- Право подтверждать корпоративный тариф.
--
-- Отдельным правом, а не в довесок к «contract-prices:write». Прислать свой
-- договор — действие интеграции: его делает система, и ошибка тут правится
-- повторной отправкой. Вынести решение по ЧУЖОМУ тарифу — действие человека,
-- отвечающего деньгами: после него по этим ценам платят.
--
-- Выдаётся живым ключам сразу: право, которого никому не выдано, ничем не
-- отличается от отсутствующего эндпоинта.
UPDATE "partner_api_key"
SET "scopes" = array_append("scopes", 'corporate-tariff:review')
WHERE "is_active" = TRUE
  AND NOT ('corporate-tariff:review' = ANY("scopes"));
