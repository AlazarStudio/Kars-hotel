import { ConflictException } from '@nestjs/common';

/**
 * МЕСТ В НОМЕРЕ НЕ БОЛЬШЕ, ЧЕМ ВМЕЩАЕТ КАТЕГОРИЯ (19.11.2026).
 *
 * Продажа и цены считают людей по категории: партнёр получает отказ сверх её
 * максимума, тарифы заводятся до него же. Номер на 2 места в категории 1–1
 * обещал второе место, которое продать нельзя. Поэтому правило одно: число
 * мест номера ограничено максимумом категории — при создании, правке, смене
 * категории и восстановлении из архива. Обратная сторона — в room-types:
 * максимум категории нельзя опустить ниже мест её номеров.
 */
export function assertRoomFitsCategory(
  capacity: number,
  category: { name: string; maxOccupancy: number },
): void {
  if (capacity > category.maxOccupancy) {
    throw new ConflictException(
      `Мест в номере — ${capacity}, а категория «${category.name}» вмещает до ${category.maxOccupancy} чел. ` +
        'Поднимите максимум категории или уменьшите число мест.',
    );
  }
}
