/* ВРЕМЯ ПРИЛЁТА И ОТЪЕЗДА И РЕЙС БРОНИ ПАРТНЁРА (24.10.2026, правка заказчика
 * Kars Avia: «со стороны гостиницы в бронях видна дата, но не видно время
 * прибытия»). Даты брони остаются датами — по ним считаются ночи, места и цена,
 * а время из заявки партнёра едет рядом: у квартир нет круглосуточной стойки,
 * и без времени экипаж встречать некому.
 *
 * Местное время текстом «ГГГГ-ММ-ДДTЧЧ:ММ», без пояса — как его видит
 * диспетчер. Метку времени с поясом пересчитали бы сервер и браузер, и прилёт
 * в 02:00 стал бы у гостиницы 05:00. Ведёт его партнёр: кабинет гостиницы его
 * не меняет (поля нет в правке кабинета, а сервис берёт время только из
 * партнёрского API). */

export const LOCAL_DATE_TIME = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])T([01]\d|2[0-3]):[0-5]\d$/;
export const LOCAL_DATE_TIME_MESSAGE = 'Время — местное, «ГГГГ-ММ-ДДTЧЧ:ММ», без пояса';

