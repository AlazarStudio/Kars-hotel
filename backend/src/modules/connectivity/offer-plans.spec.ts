import { offerPlanIds } from './offer-plans';

/* ПРЕДЛОЖЕНИЕ БЕЗ ЦЕНЫ — ЭТО ЛОЖЬ О ДОГОВОРЕ (11.11.2026).
 *
 * applies отвечает про один день (есть ли цена договора на день заезда), а
 * предложение — про весь срок и конкретную категорию с числом гостей. Тариф,
 * применимый по договору, но не посчитанный на эти ночи, нельзя показывать
 * «по договору»: его цифры пришли бы из своих строк отеля, то есть из копии,
 * от которой уходили. */

describe('offerPlanIds — применимый И посчитанный', () => {
  it('применимый и посчитанный предлагается', () => {
    // База: обе стороны сходятся — тариф и по договору, и по цене на эти ночи.
    expect(offerPlanIds(new Set(['corp']), [{ ratePlanId: 'corp', total: '15000.00' }])).toEqual(
      new Set(['corp']),
    );
  });

  it('применимый, но без цены на весь срок — не предлагается', () => {
    /* Риск: priceByPlan не смог посчитать хоть одну ночь. Показать такой тариф
       «по договору» значило бы отдать цену из других строк или упасть в
       запасную, а оператор заплатил бы не по договору. */
    expect(offerPlanIds(new Set(['corp']), [{ ratePlanId: 'corp', total: null }])).toEqual(
      new Set(),
    );
  });

  it('не применимый по договору не предлагается, даже если посчитан', () => {
    /* Риск: у тарифа нет цены договора на день заезда (чужая ДС, другой день).
       Его цена посчитана по своим строкам — предлагать её как договорную
       нельзя. */
    expect(offerPlanIds(new Set(), [{ ratePlanId: 'corp', total: '15000.00' }])).toEqual(new Set());
  });

  it('пустые входы — пустой набор', () => {
    // Риск: пустой запрос не должен превращаться в «предлагаем всё» или падать.
    expect(offerPlanIds(new Set(), [])).toEqual(new Set());
  });
});
